import {readFile,writeFile} from "node:fs/promises";

const base = new URL("../",import.meta.url);
const read = path => readFile(new URL(path,base),"utf-8");
const [schema, history, expansion, emailCopy, outreach, service, transport, graph, seed, worker] = await Promise.all([
  read("docs/ontology.json"),read("src/engagement-agent.mjs"),read("src/expansion.mjs"),read("src/email-copy.mjs"),read("src/outreach.mjs"),read("src/service.mjs"),read("src/mcp.mjs"),
  read("visual/Endor_CS_Knowledge_Graph.html"),read("data/hosted_seed.json"),read("worker/site.mjs"),
]);
const content = [
  "/* Generated by scripts/bundle-worker.mjs. */",
  "const SITE_ONTOLOGY = " + JSON.stringify(JSON.parse(schema)) + ";",
  "const SITE_SEED = " + JSON.stringify(JSON.parse(seed)) + ";",
  "const SITE_GRAPH = " + JSON.stringify(graph) + ";",
  history, emailCopy, ...[expansion,outreach,service,transport].map(source => source.replace(/^import .*from "\.\/[^"\n]+";\r?\n/gm,"")), worker,
].join("\n");
await writeFile(new URL("worker/index.js",base),content);
